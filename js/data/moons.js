for (const s of Object.values(SYSTEMS)) {
  s.moons = s.moons.filter((x) => x.latin && x.a > 0).sort((a, b) => a.a - b.a);
  s.moons.forEach((x) => {
    x.id = x.latin.toLowerCase();
    x.system = s.id;
    x.retro = x.p < 0;
  });
  s.named = s.moons.length;
}

export function findMoon(id) {
  for (const s of Object.values(SYSTEMS)) {
    const x = s.moons.find((mm) => mm.id === id);
    if (x) return x;
  }
  return null;
}
