export function profileFor(moon, system) {
  const g = system.groups[moon.group];
  const isJ = system.id === "jupiter";
  const kind = g.kind === "inner" ? (isJ ? "inner_j" : "inner_s") : (isJ ? "irr_j" : "irr_s");
  const K = KIND[kind];
  const seed = [...moon.id].reduce((s, c) => s * 31 + c.charCodeAt(0), 7) >>> 0;
  const rnd = mulberry(seed);
  const elong = moon.r > 150 ? 0.05 : 0.25 + rnd() * 0.35;
  const axes = [1 + elong, 1 - elong * 0.3 + rnd() * 0.1, 1 - elong * 0.5];
  let shape = { axes, seed: seed % 997, rough: 0.12 + rnd() * 0.1 };
  if (moon.id === "pan") shape = { axes: [1.2, 1.15, 0.77], seed: 3, rough: 0.03, ridge: 0.32, ridgeW: 0.16 };
  if (moon.id === "atlas" || moon.id === "daphnis") shape = { axes: [1.2, 1.1, 0.72], seed: 4, rough: 0.04, ridge: 0.22, ridgeW: 0.14 };
  if (moon.id === "methone") shape = { axes: [1.3, 0.85, 0.82], seed: 5, rough: 0 };
  if (moon.id === "janus" || moon.id === "epimetheus") shape = { axes: [1.2, 1.0, 0.85], seed: 6, rough: 0.1 };
  const R = moon.r;
  const dist = moon.a >= 1e6 ? `${(moon.a / 1e6).toLocaleString("ru-RU", { maximumFractionDigits: 2 })} млн км` : `${Math.round(moon.a).toLocaleString("ru-RU")} км`;
  const per = Math.abs(moon.p);
  return {
    id: moon.id, name: moon.name, latin: moon.latin, type: "moon", parent: system.id, radius: R, generic: true,
    shape, look: K.look(seed % 1000),
    tagline: `${moon.retro ? "Обратный" : "Прямой"} ${g.kind === "inner" ? "внутренний" : "нерегулярный"} спутник ${isJ ? "Юпитера" : "Сатурна"} · ${g.name}.`,
    stats: [
      ["Радиус", `≈${R.toLocaleString("ru-RU")}`, "км"],
      ["Расстояние", dist, ""],
      ["Период обращения", `${per.toLocaleString("ru-RU", { maximumFractionDigits: 2 })}`, "сут"],
      ["Наклон орбиты", moon.i.toLocaleString("ru-RU"), "°"],
      ["Направление", moon.retro ? "обратное ↺" : "прямое ↻", ""],
      ["Плотность", K.density, "г/см³"],
      ["Открыт", `${moon.year}`, ""],
    ],
    layers: K.layers(R),
    about: [K.about, g.desc, ...(NOTES[moon.id] || [])],
    history: [[String(moon.year), `Открыт: ${moon.by}.`]],
    facts: NOTES[moon.id] ? [] : [`Чтобы облететь ${isJ ? "Юпитер" : "Сатурн"}, ему нужно ${per >= 365 ? (per / 365.25).toLocaleString("ru-RU", { maximumFractionDigits: 1 }) + " земного года" : Math.round(per * 24).toLocaleString("ru-RU") + " часов"}.`],
  };
}
